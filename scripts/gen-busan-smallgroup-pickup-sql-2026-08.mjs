/**
 * DB half of the Busan small-group hotel-pickup re-timing (owner 2026-08-05).
 *
 * 🔴 WITHOUT THIS FILE THE REPO CHANGE IS INVISIBLE. TOUR_PRODUCT_USE_SUPABASE=1,
 *    so /tour-product/[slug] renders tour_product_pages.detail_payload.
 *
 * The bundle changed shape, not just strings — a stop was inserted (Haeundae
 * Beach) and every stop after it renumbered — so unlike the sibling day-tour
 * file this one replaces whole blocks rather than patching leaf paths:
 * itineraryStops, routeFlowStops, routePhases, pickup_dropoff, hero,
 * catalog_card, practicalAccordionItems, bookingSupportSteps, staticQuestions,
 * routeShapeIntro, whyTourWorks, matching_profile, seo.
 *
 * Every UPDATE is keyed on (slug, locale) and writes a value computed from the
 * bundle, so re-running is a no-op. It does NOT touch price, is_active or
 * is_published.
 *
 * de/fr/it/ru rows are staged translations — TOUR_PRODUCT_FALLBACK_URL_LOCALES
 * still serves them as EN, so writing them changes nothing a guest sees today
 * and keeps the staged rows from going stale.
 *
 * Usage: node scripts/gen-busan-smallgroup-pickup-sql-2026-08.mjs
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const REPO = path.join(__dirname, '..');
const SLUG = 'busan-small-group-yonggungsa-skycapsule-gamcheon-tour';
const BASE = ['en', 'ko', 'ja', 'zh', 'zh-TW', 'es'];
const STAGED = ['de', 'fr', 'it', 'ru'];
const OUT = path.join(
  REPO,
  'supabase',
  'pending-db-apply',
  '2026-08-05-14-busan-smallgroup-hotel-pickup.sql'
);

/** Top-level bundle keys that changed and are read by the render path. */
const BLOCKS = [
  'seo',
  'catalog_card',
  'hero',
  'itineraryStops',
  'routeFlowStops',
  'routePhases',
  'routeShapeIntro',
  'whyTourWorks',
  'practicalAccordionItems',
  'bookingSupportSteps',
  'staticQuestions',
  'pickup_dropoff',
  'matching_profile',
];

const lit = (s) => `'${String(s).replace(/'/g, "''")}'`;
const jsonb = (v) => `${lit(JSON.stringify(v))}::jsonb`;

const read = (loc) =>
  JSON.parse(
    fs.readFileSync(
      path.join(REPO, 'components/product-tour-static', SLUG, `${SLUG}.${loc}.json`),
      'utf8'
    )
  );

const en = read('en');

const out = [];
out.push(`-- =============================================================================
-- Busan small-group tour — hotel pickup + re-timed day (owner instruction 2026-08-05)
-- =============================================================================
-- Generated by scripts/gen-busan-smallgroup-pickup-sql-2026-08.mjs from the
-- bundles produced by scripts/build-busan-smallgroup-2026-08.mjs.
--
-- Pickup is no longer three subway stations. It is door-to-door pickup at
-- downtown Busan hotels between 09:00 and 10:00, and the owner set the rest of
-- the day:
--
--   09:00–10:00  hotel pickup (Seomyeon / Nampo-dong–Busan Station / Haeundae)
--   10:20–11:20  Haedong Yonggungsa
--   11:40–13:20  Cheongsapo — Daritdol skywalk, then Sky Capsule to Mipo
--   13:25–14:10  lunch          ← derived: the only gap in the owner's list
--   14:10–14:30  Haeundae Beach ← NEW stop
--   15:10–16:10  Gamcheon Culture Village
--   16:30–17:00  Dakbatgol Mural Village
--   17:10–18:20  drop-offs      ← derived: the published +20/+20/+30 intervals
--
-- ⚠ The day is now ≈9 hours, not the ≈10 the card claimed. duration_label and
--   tours.duration are updated below. matching_profile.duration_hours was
--   already 9, so this closes a gap rather than opening one.
--
-- 🔴 WITHOUT THIS FILE THE REPO CHANGE IS INVISIBLE. TOUR_PRODUCT_USE_SUPABASE=1,
--    so the page renders detail_payload, not the static bundle.
--
-- NOT IN THIS FILE: price, is_active, is_published, tour_product_offers.
-- page_sections.* mirrors are skipped — segments.ts marks that block DEAD and a
-- test asserts the render path never reads it.
--
-- Idempotent: every statement is an UPDATE keyed on (slug) or (slug, locale)
-- writing a computed value; re-running changes nothing.
--
-- AFTER APPLYING:
--   node scripts/import-match-v18.mjs --single ${SLUG}
-- =============================================================================

BEGIN;

-- ---------------------------------------------------------------------------
-- tours — card duration + the schedule the list/checkout surfaces read
-- ---------------------------------------------------------------------------
UPDATE public.tours SET
  duration = ${lit(en.catalog_card.duration)},
  schedule = ${jsonb(
    en.itineraryStops.map((s) => ({
      time: s.time,
      title: s.name,
      description: s.category,
    }))
  )},
  pickup_points_count = 1,
  dropoff_points_count = ${en.pickup_dropoff.return.length},
  updated_at = NOW()
WHERE slug = ${lit(SLUG)};
`);

let stmts = 1;
for (const loc of [...BASE, ...STAGED]) {
  const d = read(loc);
  const sets = BLOCKS.map((k) => `    jsonb_set(`).join('');
  // Build a single nested jsonb_set chain so the row is rewritten once.
  let expr = 'detail_payload';
  for (const k of BLOCKS) {
    expr = `jsonb_set(${expr}, '{"${k}"}', ${jsonb(d[k])}, true)`;
  }
  void sets;

  out.push(`-- ---------------------------------------------------------------------------
-- locale = ${loc}${STAGED.includes(loc) ? '  (staged — served as EN until the i18n gate opens)' : ''}
-- ---------------------------------------------------------------------------
UPDATE public.tour_product_pages SET
  duration_label = ${lit(d.catalog_card.duration)},
  stops_count = ${d.catalog_card.stopsCount},
  detail_payload = ${expr},
  updated_at = NOW()
WHERE slug = ${lit(SLUG)} AND locale = ${lit(loc)};
`);
  stmts += 1;
}

out.push(`COMMIT;

-- Verify:
--   SELECT locale, duration_label, stops_count,
--          detail_payload #>> '{pickup_dropoff,departure,0,time}' AS pickup_window,
--          detail_payload #>> '{itineraryStops,5,name}'           AS stop_6
--     FROM public.tour_product_pages
--    WHERE slug = ${lit(SLUG)}
--    ORDER BY locale;
-- Expect pickup_window = 09:00–10:00 and stop_6 = the Haeundae Beach stop.
`);

fs.writeFileSync(OUT, out.join('\n'), 'utf8');
console.log(`${path.relative(REPO, OUT)} — ${stmts} statements`);
