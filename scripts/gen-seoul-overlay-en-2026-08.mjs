#!/usr/bin/env node
/**
 * Emits the EN donor-overlay masters for the two new Seoul products.
 *
 * The staged locales (de/fr/it/ru) build on the EN donor bundles, so every
 * donor-derived block they render has to arrive pre-translated through an
 * overlay file. This script extracts exactly those blocks from the EN donors so
 * the overlay masters are a mechanical copy rather than a hand transcription —
 * translators then work from these files and the builder's applyOverlayStop()
 * throws if any field goes missing.
 *
 * Run: node scripts/gen-seoul-overlay-en-2026-08.mjs
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");

const DONOR_A = "seoul-seoraksan-nami-island-morning-calm-day-tour";
const DONOR_B = "seoul-private-nami-morning-calm-petite-france";

const STOP_TEXT_FIELDS = [
  "name", "category", "duration", "description", "highlights",
  "timeUsed", "whyOnRoute", "visitBasics", "convenience", "smartNotes",
];

function load(slug, loc = "en") {
  return JSON.parse(
    readFileSync(path.join(ROOT, "components/product-tour-static", slug, `${slug}.${loc}.json`), "utf8"),
  );
}

function pickStop(stop) {
  const out = {};
  for (const k of STOP_TEXT_FIELDS) {
    if (k in stop && stop[k] !== undefined) out[k] = stop[k];
  }
  return out;
}

const a = load(DONOR_A);
const b = load(DONOR_B);

const shared = {
  subnavItems: a.subnavItems,
  practicalItems: a.practicalAccordionItems,
  practicalWeatherStatic: a.practicalWeatherStatic,
  bookingTrustItems: a.bookingTrustItems,
  bookingSupportSteps: a.bookingSupportSteps,
  reviewsSummary: a.reviewsSummary,
};

const gapyeong = {
  _note:
    "EN overlay master for seoul-gapyeong-nami-morning-calm-petite-france-day-tour. GENERATED by scripts/gen-seoul-overlay-en-2026-08.mjs — do not hand-edit this file; edit the donors or the generator. Translators: copy this shape to de/fr/it/ru and translate every string value. Keys, structure and array lengths must be preserved exactly — the builder throws on any missing stop field. Do NOT translate practicalItems[].id or subnavItems[].id.",
  namiStop: pickStop(a.itineraryStops[2]),
  gmcStop: pickStop(a.itineraryStops[3]),
  petiteStop: pickStop(b.itineraryStops[2]),
  ...shared,
};

const winter = {
  _note:
    "EN overlay master for seoul-winter-seoraksan-nami-eobi-ice-valley-day-tour. GENERATED by scripts/gen-seoul-overlay-en-2026-08.mjs — do not hand-edit. Translators: copy this shape to de/fr/it/ru and translate every string value, preserving keys, structure and array lengths. Do NOT translate practicalItems[].id or subnavItems[].id.",
  seoraksanStop: pickStop(a.itineraryStops[1]),
  namiStop: pickStop(a.itineraryStops[2]),
  ...shared,
};

for (const [dir, doc] of [
  ["seoul-gapyeong-content", gapyeong],
  ["seoul-winter-eobi-content", winter],
]) {
  const outDir = path.join(__dirname, dir, "donor-overlay");
  mkdirSync(outDir, { recursive: true });
  const file = path.join(outDir, "en.json");
  writeFileSync(file, JSON.stringify(doc, null, 2) + "\n", "utf8");
  console.log(`✓ ${path.relative(ROOT, file)} (${(JSON.stringify(doc).length / 1024).toFixed(0)} KB)`);
}
