/**
 * Emits the DB half of the Busan Top Attractions pickup realignment.
 *
 * 🔴 WITHOUT THIS FILE THE REPO CHANGE IS INVISIBLE. TOUR_PRODUCT_USE_SUPABASE=1,
 *    so /tour-product/[slug] renders tour_product_pages.detail_payload and the
 *    static bundle is only the fallback.
 *
 * Every statement is a surgical `jsonb_set` on ONE path, guarded by a WHERE
 * clause that asserts the DB still holds the pre-change value (read from git
 * HEAD, i.e. the bundle as it was before
 * scripts/align-busan-top-attractions-pickup-2026-08.mjs ran). That makes the
 * file idempotent and unable to clobber a value edited through the admin
 * Product Editor, which writes the same column.
 *
 * `pickup_dropoff` is the exception: the DB rows carry localized objects that
 * never existed in the non-EN bundles (they came from the one-off
 * scripts/gen_pickup_sql.js run) and their coordinates predate
 * scripts/fix-pickup-dropoff-coords.mjs. So that one path is written whole,
 * guarded only on "first departure is not already 08:10".
 *
 * page_sections.* mirrors are deliberately NOT written — segments.ts marks the
 * block DEAD and a test asserts the render path never reads it.
 *
 * Usage: node scripts/gen-busan-top-attractions-pickup-sql-2026-08.mjs
 */

import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const REPO = path.join(__dirname, '..');
const SLUG = 'busan-top-attractions-day-tour';
const LOCALES = ['en', 'ko', 'ja', 'es', 'zh', 'zh-TW'];
const OUT = path.join(
  REPO,
  'supabase',
  'pending-db-apply',
  '2026-08-05-13-busan-top-attractions-pickup.sql'
);

/** detail_payload paths that changed and are actually rendered. */
const PATHS = [
  ['hero', 'meta', 'duration'],
  ['routeShapeIntro', 'subtitle'],
  ['itineraryStops', '0', 'time'],
  ['itineraryStops', '0', 'duration'],
  ['itineraryStops', '0', 'timeUsed'],
  ['itineraryStops', '0', 'whyOnRoute'],
  ['itineraryStops', '0', 'description'],
  ['whyTourWorks', 'routeLogicSections', '1', 'items', '2', 'detail'],
  ['practicalAccordionItems', '0', 'preview'],
  ['practicalAccordionItems', '0', 'content', '0'],
  ['practicalAccordionItems', '0', 'content', '2'],
  ['staticQuestions', '8', 'answer'],
];

const rel = (locale) =>
  `components/product-tour-static/${SLUG}/${SLUG}.${locale}.json`;

function readHead(locale) {
  const raw = execFileSync('git', ['show', `HEAD:${rel(locale)}`], {
    cwd: REPO,
    encoding: 'utf8',
    maxBuffer: 64 * 1024 * 1024,
  });
  return JSON.parse(raw);
}

const readNow = (locale) =>
  JSON.parse(fs.readFileSync(path.join(REPO, rel(locale)), 'utf8'));

const at = (doc, p) => p.reduce((acc, k) => (acc == null ? acc : acc[k]), doc);

/** Postgres text literal. */
const lit = (s) => `'${String(s).replace(/'/g, "''")}'`;
/** jsonb literal from a JS value. */
const jsonb = (v) => `${lit(JSON.stringify(v))}::jsonb`;
/** '{a,b,0}' path literal — quote each token so digits stay array indexes. */
const pathLit = (p) => `'{${p.map((t) => `"${t}"`).join(',')}}'`;

const out = [];
out.push(`-- =============================================================================
-- Busan Top Attractions Day Tour — pickup order + times (owner instruction 2026-08-05)
-- =============================================================================
-- Generated by scripts/gen-busan-top-attractions-pickup-sql-2026-08.mjs from the
-- bundles rewritten by scripts/align-busan-top-attractions-pickup-2026-08.mjs.
--
--   1) 08:10  Busan Station Exit 4   (subway Line 1 exit — NOT the KTX gate)
--   2) 08:30  Seomyeon Station Exit 4
--   3) 09:10  Haeundae Station Exit 5
--
-- WAS: Seomyeon 08:30 → Busan Station 08:50 → Haeundae 09:30, and the page told
-- that story three different ways (pickup_dropoff said Seomyeon first, the
-- itinerary said Busan Station first at ~09:00, page_sections said Busan Station
-- first at 08:30). All three now say the same thing.
--
-- 🔴 WITHOUT THIS FILE THE REPO CHANGE IS INVISIBLE. TOUR_PRODUCT_USE_SUPABASE=1,
--    so the page renders tour_product_pages.detail_payload, not the bundle.
--
-- NOT IN THIS FILE, on purpose:
--   * drop-off times and every downstream stop time — the owner asked about
--     pickup; re-timing the rest of the day would be inventing numbers.
--   * the "10.5 hours" label (tours.duration, tour_product_pages.duration_label,
--     catalog_card.duration, seo.metaDescription). 08:10 → ≈19:00 is ≈10.8 h, so
--     the rounded label now understates by ~20 min. Raising it to 11 h is an
--     owner call.
--   * price, is_active, is_published — untouched.
--   * page_sections.* mirrors — segments.ts marks that block DEAD and a test
--     asserts the render path never reads it.
--
-- Idempotent: every UPDATE is guarded on the pre-change value, so re-running is
-- a no-op and a value already edited through the admin Product Editor is left
-- alone rather than clobbered.
--
-- AFTER APPLYING:
--   node scripts/import-match-v18.mjs --single ${SLUG}
-- =============================================================================

BEGIN;
`);

// ---- tours.schedule[0].time -------------------------------------------------
out.push(`-- ---------------------------------------------------------------------------
-- tours — the card / checkout schedule mirrors stop 1's time
-- ---------------------------------------------------------------------------
UPDATE public.tours SET
  schedule = jsonb_set(schedule, '{0,time}', '"≈ 08:10"'::jsonb, false),
  updated_at = NOW()
WHERE slug = ${lit(SLUG)}
  AND schedule #>> '{0,time}' = '≈ 09:00';
`);

let stmts = 1;
for (const locale of LOCALES) {
  const head = readHead(locale);
  const now = readNow(locale);
  const lines = [];

  for (const p of PATHS) {
    const before = at(head, p);
    const after = at(now, p);
    if (before === undefined) throw new Error(`${locale}: missing path ${p.join('.')} at HEAD`);
    if (JSON.stringify(before) === JSON.stringify(after)) continue;

    // #>> returns text; for an array path compare the whole element with #> instead.
    const guard = Array.isArray(before)
      ? `detail_payload #> ${pathLit(p)} = ${jsonb(before)}`
      : `detail_payload #>> ${pathLit(p)} = ${lit(before)}`;

    lines.push(`UPDATE public.tour_product_pages SET
  detail_payload = jsonb_set(detail_payload, ${pathLit(p)}, ${jsonb(after)}, false),
  updated_at = NOW()
WHERE slug = ${lit(SLUG)} AND locale = ${lit(locale)}
  AND ${guard};`);
    stmts += 1;
  }

  // pickup_dropoff — written whole (see header)
  lines.push(`UPDATE public.tour_product_pages SET
  detail_payload = jsonb_set(detail_payload, '{"pickup_dropoff"}', ${jsonb(now.pickup_dropoff)}, true),
  updated_at = NOW()
WHERE slug = ${lit(SLUG)} AND locale = ${lit(locale)}
  AND detail_payload #>> '{"pickup_dropoff","departure","0","time"}' IS DISTINCT FROM '08:10';`);
  stmts += 1;

  out.push(`-- ---------------------------------------------------------------------------
-- locale = ${locale}
-- ---------------------------------------------------------------------------
${lines.join('\n\n')}
`);
}

out.push(`COMMIT;

-- Verify (expect three rows per locale, in this order):
--   SELECT locale,
--          jsonb_array_elements(detail_payload -> 'pickup_dropoff' -> 'departure') AS stop
--     FROM public.tour_product_pages
--    WHERE slug = ${lit(SLUG)}
--    ORDER BY locale;
`);

fs.writeFileSync(OUT, out.join('\n'), 'utf8');
console.log(`${path.relative(REPO, OUT)} — ${stmts} statements`);
