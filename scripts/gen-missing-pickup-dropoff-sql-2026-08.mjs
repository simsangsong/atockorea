/**
 * DB half of the missing-pickup-card repair.
 *
 * 🔴 THE REPO FIX ALONE CHANGES NOTHING FOR GUESTS. TOUR_PRODUCT_USE_SUPABASE=1,
 *    so the page renders tour_product_pages.detail_payload; a bundle that has
 *    pickup_dropoff does not help a DB row that does not.
 *
 * One statement per (slug, locale): write the whole pickup_dropoff object with
 * create_missing = true, guarded so a row that already carries a departure list
 * is left exactly as it is. Re-running is a no-op, and nothing that was already
 * correct — including anything edited through the admin Product Editor — is
 * touched.
 *
 * Usage: node scripts/gen-missing-pickup-dropoff-sql-2026-08.mjs
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const REPO = path.join(__dirname, '..');
const LOCALES = ['ko', 'ja', 'zh', 'zh-TW', 'es'];
const SLUGS = [
  'jeju-grand-highlights-loop',
  'jeju-west-south-full-day-authentic-tour',
  'jeju-hydrangea-festival-tour-southwest-route',
  'busan-small-group-sightseeing-tour-cruise-passengers',
  'incheon-seoul-private-car-shore-excursion-cruise',
  'from-incheon-seoul-day-tour-cruise-guests',
];
const OUT = path.join(REPO, 'supabase', 'pending-db-apply', '2026-08-05-15-missing-pickup-dropoff.sql');

/**
 * Block present in every locale, but the `notes` paragraph stayed raw English
 * on the CJK/ES pages. Same repair, narrower path.
 */
const NOTES_ONLY = [
  'busan-gyeongju-unesco-legacy-tour-national-museum',
  'busan-plum-cherry-blossom-day-tour-to-yangsan-gyeongju',
  'busan-spring-cherry-blossom-gyeongju-highlights-day-tour',
];

const lit = (s) => `'${String(s).replace(/'/g, "''")}'`;
const jsonb = (v) => `${lit(JSON.stringify(v))}::jsonb`;

const out = [];
out.push(`-- =============================================================================
-- Missing "Pickup & Map" section on non-EN pages — repair (2026-08-05)
-- =============================================================================
-- Generated by scripts/gen-missing-pickup-dropoff-sql-2026-08.mjs from the
-- bundles filled by scripts/fill-missing-locale-pickup-dropoff-2026-08.mjs.
--
-- 🔴 WHAT WAS BROKEN, AND IT WAS LIVE. The detail page renders the entire
--    "Pickup & Map" section only when detail_payload.pickup_dropoff exists
--    (TourProductDetailClient.tsx gates on vm.pickup_dropoff; loadTourProductPage
--    .ts spreads the key only when non-null). Where it was missing, guests saw
--    the timeline run straight from the last stop into "What's included" — no
--    map, no pickup list, no drop-off list.
--
--    Measured on production by counting id="pickup-dropoff" in the server HTML:
--      busan-top-attractions-day-tour              en OK · ko/ja/zh-TW/es MISSING
--      jeju-grand-highlights-loop                  en OK · ko/ja/zh-TW/es MISSING
--      busan-small-group-sightseeing-…-passengers  en OK · ko MISSING
--      incheon-seoul-private-car-shore-excursion…  en OK · ko MISSING
--    ⚠ /zh/ renders client-side and returns a ~32 KB shell, so it cannot be
--      measured that way — a 0 there is not evidence of a defect.
--
--    busan-top-attractions-day-tour is repaired by 2026-08-05-13 (same session)
--    and is deliberately not repeated here.
--
-- ROOT CAUSE: the block only ever existed in the EN bundle. A one-off run of
-- scripts/gen_pickup_sql.js wrote localized copies straight to the DB and never
-- wrote them back to the repo, so any later statement that rebuilt a locale's
-- detail_payload from its bundle silently dropped the section. The repo is
-- fixed in the same commit, which is what stops this recurring.
--
-- Blocked products (jeju-west-south…, jeju-hydrangea-…-southwest-route,
-- from-incheon-seoul-day-tour-cruise-guests) are included on purpose: cheap
-- now, and otherwise they ship the same hole the day they are re-opened.
--
-- Idempotent AND non-destructive: each statement writes only where the row has
-- no departure list, so a locale that is already correct is never rewritten.
--
-- Touches nothing else — no price, no is_active, no is_published.
-- =============================================================================

BEGIN;
`);

let stmts = 0;
for (const slug of SLUGS) {
  const lines = [];
  for (const loc of LOCALES) {
    const file = path.join(REPO, 'components/product-tour-static', slug, `${slug}.${loc}.json`);
    if (!fs.existsSync(file)) continue;
    const doc = JSON.parse(fs.readFileSync(file, 'utf8'));
    if (!doc.pickup_dropoff?.departure?.length) continue;

    lines.push(`UPDATE public.tour_product_pages SET
  detail_payload = jsonb_set(detail_payload, '{"pickup_dropoff"}', ${jsonb(doc.pickup_dropoff)}, true),
  updated_at = NOW()
WHERE slug = ${lit(slug)} AND locale = ${lit(loc)}
  AND COALESCE(jsonb_array_length(detail_payload #> '{"pickup_dropoff","departure"}'), 0) = 0;`);
    stmts += 1;
  }
  out.push(`-- ---------------------------------------------------------------------------
-- ${slug}
-- ---------------------------------------------------------------------------
${lines.join('\n\n')}
`);
}

// ── notes-only repair ─────────────────────────────────────────────────────
for (const slug of NOTES_ONLY) {
  const enDoc = JSON.parse(
    fs.readFileSync(path.join(REPO, 'components/product-tour-static', slug, `${slug}.en.json`), 'utf8')
  );
  const enNotes = enDoc.pickup_dropoff?.notes ?? [];
  const lines = [];
  for (const loc of LOCALES) {
    const file = path.join(REPO, 'components/product-tour-static', slug, `${slug}.${loc}.json`);
    if (!fs.existsSync(file)) continue;
    const doc = JSON.parse(fs.readFileSync(file, 'utf8'));
    const notes = doc.pickup_dropoff?.notes;
    if (!Array.isArray(notes) || notes.length === 0) continue;

    // Guarded on the English original still being in place, so a note already
    // translated by hand (or through the admin editor) is never overwritten.
    lines.push(`UPDATE public.tour_product_pages SET
  detail_payload = jsonb_set(detail_payload, '{"pickup_dropoff","notes"}', ${jsonb(notes)}, false),
  updated_at = NOW()
WHERE slug = ${lit(slug)} AND locale = ${lit(loc)}
  AND detail_payload #>> '{"pickup_dropoff","notes","0"}' = ${lit(enNotes[0])};`);
    stmts += 1;
  }
  if (lines.length === 0) continue;
  out.push(`-- ---------------------------------------------------------------------------
-- ${slug} — notes were still English on the non-EN pages
-- ---------------------------------------------------------------------------
${lines.join('\n\n')}
`);
}

out.push(`COMMIT;

-- Verify — every row should report a non-zero departure count:
--   SELECT slug, locale,
--          COALESCE(jsonb_array_length(detail_payload #> '{pickup_dropoff,departure}'), 0) AS pickup_points
--     FROM public.tour_product_pages
--    ORDER BY pickup_points, slug, locale;
-- Any remaining 0 is a page rendering with no Pickup & Map section at all.
`);

fs.writeFileSync(OUT, out.join('\n'), 'utf8');
console.log(`${path.relative(REPO, OUT)} — ${stmts} statements`);
