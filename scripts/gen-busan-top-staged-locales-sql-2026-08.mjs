/**
 * Busan Top Attractions — the same pickup realignment, for the STAGED locales.
 *
 * 2026-08-05-13 moved the six content locales to Busan Station 08:10 → Seomyeon
 * 08:30 → Haeundae 09:10. It could not touch de/fr/it/ru because those four are
 * generated from bundles that do not exist: the product has six bundle files,
 * and the staged translations live only as DB rows. So they kept telling the old
 * story (Seomyeon first at 08:30, stop 1 at ≈09:00) while every other locale had
 * moved on.
 *
 * They are not customer-visible today — TOUR_PRODUCT_FALLBACK_URL_LOCALES still
 * serves de/fr/it/ru as English — which is exactly why this is safe to write and
 * exactly why it would otherwise rot unnoticed until the day that gate opens.
 *
 * The translations were not redone. English changed surgically, so each locale
 * received the same surgical edit against its existing translation: the times,
 * the west→east ordering, the ≈09:50 arrival, and the "about 15 minutes"
 * phrasing that replaced "±30 min". Each locale keeps its own clock convention
 * (de "08:10 Uhr", fr "08 h 10", it "ore 8:10", ru "08:10").
 *
 * Coordinates and times in pickup_dropoff are copied from the ENGLISH row rather
 * than re-derived, so the four staged rows cannot drift from the six live ones.
 *
 * Every statement is guarded on the pre-change value read out of the database,
 * so re-running is a no-op and a row edited through the admin Product Editor is
 * left alone rather than clobbered. Nothing else is touched — no price, no
 * is_active, no is_published, and no row outside de/fr/it/ru.
 *
 * Usage: node scripts/gen-busan-top-staged-locales-sql-2026-08.mjs
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const REPO = path.join(__dirname, '..');
const SLUG = 'busan-top-attractions-day-tour';
const DATA = path.join(__dirname, 'busan-top-staged-locale-pickup-2026-08.json');
const OUT = path.join(
  REPO,
  'supabase',
  'pending-db-apply',
  '2026-08-05-16-busan-top-staged-locales-pickup.sql'
);

const lit = (s) => `'${String(s).replace(/'/g, "''")}'`;
const jsonb = (v) => `${lit(JSON.stringify(v))}::jsonb`;
/** '{a,b,0}' path literal — quote each token so digits stay array indexes. */
const pathLit = (p) => `'{${p.map((t) => `"${t}"`).join(',')}}'`;

const data = JSON.parse(fs.readFileSync(DATA, 'utf8'));

const out = [];
out.push(`-- =============================================================================
-- Busan Top Attractions — pickup realignment for the STAGED locales (2026-08-05)
-- =============================================================================
-- Generated by scripts/gen-busan-top-staged-locales-sql-2026-08.mjs from
-- scripts/busan-top-staged-locale-pickup-2026-08.json.
--
-- 2026-08-05-13 realigned the six content locales to
--   1) 08:10  Busan Station Exit 4   2) 08:30  Seomyeon   3) 09:10  Haeundae
-- and could not reach de/fr/it/ru: this product has six bundle files, and the
-- staged translations exist only as DB rows. They were still telling the old
-- story — Seomyeon first at 08:30, stop 1 at ≈09:00.
--
-- Not customer-visible today: TOUR_PRODUCT_FALLBACK_URL_LOCALES still serves
-- these four as English. That is what makes writing them safe, and also what
-- would have let them rot unnoticed until that gate opens.
--
-- The translations were not redone — English changed surgically, so each locale
-- got the same surgical edit against its own text, keeping its clock convention
-- (de "08:10 Uhr", fr "08 h 10", it "ore 8:10", ru "08:10"). Coordinates and
-- times inside pickup_dropoff are copied from the English row, so these four
-- rows cannot drift from the six live ones.
--
-- NOT IN THIS FILE: price, is_active, is_published, any locale outside
-- de/fr/it/ru, and the "10.5 hours" label (raising it is an owner call — see
-- the header of 2026-08-05-13).
--
-- Idempotent: every UPDATE is guarded on the pre-change value, so re-running is
-- a no-op and a value edited through the admin Product Editor is left alone.
-- =============================================================================

BEGIN;
`);

let stmts = 0;
for (const [locale, spec] of Object.entries(data)) {
  const lines = [];

  for (const [pointer, { before, after }] of Object.entries(spec.leaves)) {
    const p = pointer.split('/');
    // #>> returns text; for an array path compare the whole element with #> instead.
    const guard = Array.isArray(before)
      ? `detail_payload #> ${pathLit(p)} = ${jsonb(before)}`
      : `detail_payload #>> ${pathLit(p)} = ${lit(before)}`;

    lines.push(`UPDATE public.tour_product_pages SET
  detail_payload = jsonb_set(detail_payload, ${pathLit(p)}, ${jsonb(after)}, false),
  updated_at = NOW()
WHERE slug = ${lit(SLUG)} AND locale = ${lit(locale)}
  AND ${guard};`);
    stmts += 1;
  }

  // pickup_dropoff — written whole, because the departure list is reordered.
  lines.push(`UPDATE public.tour_product_pages SET
  detail_payload = jsonb_set(detail_payload, '{"pickup_dropoff"}', ${jsonb(spec.pickup_dropoff.after)}, true),
  updated_at = NOW()
WHERE slug = ${lit(SLUG)} AND locale = ${lit(locale)}
  AND detail_payload #>> '{"pickup_dropoff","departure","0","time"}' IS DISTINCT FROM '08:10';`);
  stmts += 1;

  out.push(`-- ---------------------------------------------------------------------------
-- locale = ${locale}  (staged — served as EN until the i18n gate opens)
-- ---------------------------------------------------------------------------
${lines.join('\n\n')}
`);
}

out.push(`COMMIT;

-- Verify — all ten locales should now report the same three pickup times:
--   SELECT locale,
--          detail_payload #>> '{pickup_dropoff,departure,0,time}' AS p1,
--          detail_payload #>> '{pickup_dropoff,departure,1,time}' AS p2,
--          detail_payload #>> '{pickup_dropoff,departure,2,time}' AS p3,
--          detail_payload #>> '{itineraryStops,0,time}'           AS stop1
--     FROM public.tour_product_pages
--    WHERE slug = ${lit(SLUG)}
--    ORDER BY locale;
-- Expect 08:10 / 08:30 / 09:10 and stop1 = the localized "≈ 08:10".
`);

fs.writeFileSync(OUT, out.join('\n'), 'utf8');
console.log(`${path.relative(REPO, OUT)} — ${stmts} statements`);
