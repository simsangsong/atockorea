#!/usr/bin/env node
/**
 * Generates supabase/pending-db-apply/2026-08-04-09-pocheon-departure-days.sql
 *
 * WHY THIS FILE EXISTS — a sequencing accident, not a new decision.
 *
 * SQL 05/06 were applied to the live DB from the version of those files that
 * was on `main` at the time, which predates the Pocheon Mon/Thu/Sat departure-day
 * work. So the DB has the re-coursed Pocheon tour WITHOUT any departure-day
 * claim: `matching_profile.available_days_signature` is null and the accordion
 * item is absent in all ten locales (measured, not assumed). The bundles carry
 * it; the DB is what guests read.
 *
 * Re-applying 05/06 would fix it but those files are 640KB/480KB and are now
 * archived under applied/ as the record of what actually ran. So instead this
 * emits the DELTA: it diffs each Pocheon bundle against the row currently in
 * the database and writes one guarded statement per differing path.
 *
 * Granularity: scalars are set individually; a container whose shape changed
 * (array length, or object keys) is replaced whole at its own path, because
 * jsonb_set cannot append. Either way it is one path per statement.
 *
 * SAFETY: every statement is guarded on the value currently in the DB, so it is
 * idempotent and cannot clobber an edit made through the admin Product Editor,
 * which writes the same column. A path that no longer matches is left alone.
 *
 * Reads the DB over supabase-js with the service-role key, same as
 * scripts/apply-tour-catalog-2026-08-04.mjs:
 *   node --env-file=.env.local scripts/gen-pocheon-departure-days-sql-2026-08.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { createClient } from "@supabase/supabase-js";

const SLUG = "pocheon-sanjeong-lake-herb-island-art-valley";
const LOCALES = ["en", "ko", "ja", "zh", "zh-TW", "es", "de", "fr", "it", "ru"];
const TARGET = "supabase/pending-db-apply/2026-08-04-09-pocheon-departure-days.sql";

const SUPABASE_URL = process.env.NEXT_PUBLIC_SUPABASE_URL || process.env.SUPABASE_URL || "";
const SERVICE_KEY =
  process.env.SUPABASE_SERVICE_ROLE_KEY || process.env.SUPABASE_SERVICE_KEY || "";
if (!SUPABASE_URL || !SERVICE_KEY) {
  console.error("missing SUPABASE_URL / SUPABASE_SERVICE_ROLE_KEY — run with --env-file=.env.local");
  process.exit(1);
}
const sb = createClient(SUPABASE_URL, SERVICE_KEY, { auth: { persistSession: false } });

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const jpath = (segs) => `{${segs.map((s) => `"${String(s).replace(/"/g, '\\"')}"`).join(",")}}`;
const kind = (v) => (Array.isArray(v) ? "array" : v === null ? "null" : typeof v);

/** Collect the shallowest paths at which `want` and `have` differ. */
function diff(want, have, segs, out) {
  if (kind(want) !== kind(have)) return out.push({ segs, want, have });
  if (Array.isArray(want)) {
    if (want.length !== have.length) return out.push({ segs, want, have });
    want.forEach((v, i) => diff(v, have[i], [...segs, String(i)], out));
    return;
  }
  if (want && typeof want === "object") {
    const kw = Object.keys(want);
    const kh = Object.keys(have);
    if (kw.length !== kh.length || kw.some((k) => !kh.includes(k)))
      return out.push({ segs, want, have });
    for (const k of kw) diff(want[k], have[k], [...segs, k], out);
    return;
  }
  if (want !== have) out.push({ segs, want, have });
}

const rows = [];
let skippedDead = 0;

for (const locale of LOCALES) {
  const bundle = JSON.parse(
    readFileSync(path.join("components/product-tour-static", SLUG, `${SLUG}.${locale}.json`), "utf8"),
  );
  const { data, error } = await sb
    .from("tour_product_pages")
    .select("detail_payload")
    .eq("slug", SLUG)
    .eq("locale", locale)
    .maybeSingle();
  if (error) throw new Error(`${locale}: ${error.message}`);
  if (!data) {
    console.warn(`! ${locale}: no DB row — skipped`);
    continue;
  }
  const found = [];
  diff(bundle, data.detail_payload ?? {}, [], found);
  for (const d of found) {
    // page_sections is a DEAD mirror (segments.ts); _publication is our changelog.
    if (d.segs[0] === "page_sections" || d.segs[0] === "_publication") {
      skippedDead += 1;
      continue;
    }
    rows.push({ locale, ...d });
  }
}

const L = [];
L.push("-- =============================================================================");
L.push("-- Pocheon — Mon/Thu/Sat departure days that SQL 05/06 did not carry");
L.push("-- =============================================================================");
L.push("-- Generated by scripts/gen-pocheon-departure-days-sql-2026-08.mjs");
L.push("--");
L.push("-- SQL 05/06 were applied from the version on main at the time, which predates");
L.push("-- the departure-day work. Measured afterwards: available_days_signature was");
L.push("-- NULL and the departure-days accordion item absent in all 10 locales, so a");
L.push("-- guest could still pick any date and only hit the constraint at checkout.");
L.push("--");
L.push("-- This is the delta between each Pocheon bundle and the row now in the DB.");
L.push("-- Scalars are set individually; a container whose shape changed is replaced");
L.push("-- whole at its own path (jsonb_set cannot append).");
L.push("--");
L.push("-- SAFETY: guarded on the value currently in the DB — idempotent, and unable");
L.push("-- to clobber an admin Product Editor edit to the same column.");
L.push(`-- page_sections / _publication paths skipped: ${skippedDead}.`);
L.push(`-- Statements: ${rows.length} across ${new Set(rows.map((r) => r.locale)).size} locales.`);
L.push("-- =============================================================================");
L.push("");
L.push("BEGIN;");
L.push("");

let cursor = "";
for (const r of rows) {
  if (r.locale !== cursor) {
    cursor = r.locale;
    L.push(`-- ---- ${SLUG} [${r.locale}] ${"-".repeat(Math.max(0, 40 - r.locale.length))}`);
  }
  const p = jpath(r.segs);
  const isScalar = r.have === null || (typeof r.have !== "object" && !Array.isArray(r.have));
  L.push("UPDATE public.tour_product_pages SET");
  L.push(`  detail_payload = jsonb_set(detail_payload, ${q(p)}, ${q(JSON.stringify(r.want))}::jsonb, true),`);
  L.push("  updated_at = NOW()");
  L.push(`WHERE slug = ${q(SLUG)} AND locale = ${q(r.locale)}`);
  // Guard on the exact current value. `#>` compares the json subtree for
  // containers; `#>>` compares text for scalars. IS NOT DISTINCT FROM so a
  // genuinely absent path (the new signature key) still matches.
  if (isScalar)
    L.push(`  AND detail_payload #>> ${q(p)} IS NOT DISTINCT FROM ${r.have === null ? "NULL" : q(String(r.have))};`);
  else L.push(`  AND detail_payload #> ${q(p)} IS NOT DISTINCT FROM ${q(JSON.stringify(r.have))}::jsonb;`);
  L.push("");
}
L.push("COMMIT;");
L.push("");
L.push("-- Verify (expect 10 rows, all Mon/Thu/Sat, all with the accordion item):");
L.push("-- SELECT locale,");
L.push("--        detail_payload #>> '{matching_profile,available_days_signature}' AS days,");
L.push("--        (SELECT count(*) FROM jsonb_array_elements(");
L.push("--           COALESCE(detail_payload->'practicalAccordionItems','[]'::jsonb)) a");
L.push("--          WHERE a.value->>'id' = 'departure-days') AS accordion");
L.push("--   FROM public.tour_product_pages");
L.push("--  WHERE slug = 'pocheon-sanjeong-lake-herb-island-art-valley' ORDER BY locale;");
L.push("");

writeFileSync(TARGET, L.join("\n"), "utf8");
console.log("wrote", TARGET);
console.log(`statements: ${rows.length} | locales: ${new Set(rows.map((r) => r.locale)).size} | dead skipped: ${skippedDead}`);
const byPath = {};
for (const r of rows) byPath[r.segs.slice(0, 2).join(".")] = (byPath[r.segs.slice(0, 2).join(".")] || 0) + 1;
console.log("top paths:", JSON.stringify(byPath, null, 0));
